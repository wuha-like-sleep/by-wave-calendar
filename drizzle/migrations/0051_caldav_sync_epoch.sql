-- CalDAV 同步纪元:一个部署级别的字符串,掺进每个日历的 ctag。

-- 为什么 0050 治不了根
-- --------------------
-- 0050 的目的是「逼 CalDAV 客户端重新拉一遍带提醒的事件」,做法是把那批行的
-- updated_at 改成一个固定的过去时间戳。但集合的 ctag 是
--   md5( 该日历全部行的 max(updated_at) | 活行数 )
-- (见 src/web/caldav.ts 的 calendarCtags),而 0050 不动订阅进来的行、
-- 不动没挂提醒的行。**只要 max(updated_at) 落在那些不动的行上,ctag 一个字节
-- 都不变** —— 而 ctag 正是苹果日历用来决定「要不要重新列一遍这个日历」的那个值。
--
-- 实测:一个日历里两条事件(一条网页建的带提醒、一条最近刷新过的订阅事件),
-- 跑完 0050 前后
--   ctag BEFORE: c77eb02510f19ce130455870d9629b98   (max=2026-09-25, live=2)
--   ctag AFTER : c77eb02510f19ce130455870d9629b98   ← 没变
--   单行 etag  : 网页那条变了,订阅那条没变
-- 后果不是丢数据(删提醒那道闸门是牢的),是这部分用户的手机上提醒迟迟不出现,
-- 而发版说明会告诉他「同步一下就有了」。这是一次性的,错过不会再补。
--
-- 0050 要不要留:**留**,两条做的不是同一件事,少一条就不成。
--   · 纪元只进 ctag,不进单行 etag ——它让客户端**去列**(一次 Depth:1 PROPFIND),
--     但清单里每条的 etag 都没变,客户端一条正文都不会重下。
--   · 0050 改的是 updated_at,进的是单行 etag ——它让客户端**去下**那批正文。
-- 只有 0050 而没有纪元:客户端根本不来列,等于什么都没发生(就是现在这个 bug)。
-- 只有纪元而没有 0050:客户端来列了一遍,发现 etag 全没变,又走了,提醒还是不出现。
-- 两条都不会重复做同一件事:0050 是「这一版这批行的内容变了」,纪元是
-- 「这一版所有日历都值得重新看一眼」。

-- 语句一:加列。
-- 默认空串 = 「还没 bump 过」,是一个合法取值。默认值必须和 src/db/schema.ts、
-- 以及 src/lib/auto_migrate.ts 里的兜底补丁一字不差 —— 三处只要有一处写别的,
-- 「补上了」反而是改了行为。
ALTER TABLE site_settings ADD COLUMN IF NOT EXISTS caldav_sync_epoch text NOT NULL DEFAULT '';--> statement-breakpoint

-- 语句二:这一版的 bump 本身。
--
-- 为什么写死一个字面量、而不是 now() 或者 epoch || '+1':
-- src/lib/auto_migrate.ts 每次开机都跑迁移器,而历史上出现过「迁移器记账和
-- 真实 schema 对不上、整条链重放」的情况。写 now() / 自增的话,第二遍会再 bump
-- 一次,全体客户端再白列一轮,而且「跑两遍结果一致」这条根本没法断言。
-- 写死字面量 + `IS DISTINCT FROM` 之后,第二遍匹配不到任何行,是真正的 no-op。
--
-- 为什么用 `IS DISTINCT FROM` 而不是 `<`(或者干脆换成自增整数):
-- 这一列以后会有第二个 bump 源(后台按钮,见 site_settings.ts 的
-- bumpCaldavSyncEpoch)。整数 + `<` 的话,管理员按几次就能把值推过下一版的常量,
-- 那一版的强制重拉会被静默吞掉 —— 没有报错、没有日志,只是一批用户的手机上
-- 少了点东西。文本 + `IS DISTINCT FROM` 不需要任何顺序假设:重放匹配不到行,
-- 而后台写进去的串和任何一版的常量都不同,两个源互相遮不住。
--
-- 整条链一次性重放(0051 设 A、将来的 00NN 设 B)也是安全的:末尾以最后一条为准,
-- 和重放前的值相同,净效果是 no-op。
--
-- 匹配不到行的唯一情况是**全新安装**——site_settings 那一行是第一次读设置时
-- 才懒插入的(src/lib/site_settings.ts loadFromDb),此刻还不存在,于是它带着
-- 默认的空串诞生。全新安装没有任何客户端手上拿着过期副本,这正是对的。
UPDATE site_settings
   SET caldav_sync_epoch = '2026-09-21-alarm-vevent'
 WHERE caldav_sync_epoch IS DISTINCT FROM '2026-09-21-alarm-vevent';
