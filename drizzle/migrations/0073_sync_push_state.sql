-- 同步推送（增量同步第三批：推送触发增量、轮询降级兜底）的每用户水位。
--
-- 一、为什么要有这张表。前两批把「拉」做成了增量（syncToken），但触发
-- 拉取的时机还靠页面每 30 秒轮询：改动发生在别人设备上时，打开着的页面
-- 最迟 30 秒才知道，关掉的页面更是无从谈起。第三批给服务端加一个清扫器
-- （lib/sync_push.ts，20 秒一跳）：扫 event_changes，把「你能看见的变化
-- 已经超过上次推送到的位置」的人找出来，发一条只有信号、没有任何事件
-- 数据的 Web Push；页面被唤醒后自己走既有的增量拉取。轮询不删，降级为
-- 兜底（有活跃推送订阅时放宽到 5 分钟）。
--
-- 二、为什么水位要落库、而且只在推送送达后才推进。进程内水位重启就没
-- 了：归零会把 30 天保留期内的全部历史重推一遍（滥发），置成当前水位
-- 又会漏掉停机期间的变化（那些只能等轮询兜底，不算错，但能避免就避
-- 免）。落库 + 「推送服务至少收下一个端点（sent ≥ 1）才推进」是最保守
-- 的组合：宁可下轮重推一条，不可把没送达的变化标成已通知。
--
-- 三、表的形状。一行一个用户，只给有 Web Push 订阅的人建 —— 没订阅的
-- 人永远不会被推送，清扫器连行都不给他建。pushed_seq 是 event_changes
-- 的全表序号（与同步令牌同一个水位口径）；last_pushed_at 是防滥发最小
-- 间隔（30 秒）的判据，和序号同行存。user_id 挂 CASCADE：这行只是账
-- 号的附属记账，账号删了它留着没有意义 —— 与 event_changes 那种「墓碑
-- 必须活得比本体久」的表正好相反，所以那边不设外键、这边要设。
CREATE TABLE IF NOT EXISTS "sync_push_state" (
  "user_id" uuid PRIMARY KEY REFERENCES "users"("id") ON DELETE cascade,
  "pushed_seq" bigint NOT NULL DEFAULT 0,
  "last_pushed_at" timestamp with time zone
);
