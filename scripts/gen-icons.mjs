// Website, PWA, email, iOS and Android defaults from the shared vector mark.
// Run from the repository root: node scripts/gen-icons.mjs
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { brandSvg, brandPng } from './brand-assets.mjs';

await mkdir('src/public/icons', { recursive: true });
await writeFile('src/public/favicon.svg', brandSvg(32));
await writeFile('src/views/partials/default-brand.ejs', '<%# Generated by scripts/gen-icons.mjs from src/public/brand/logo.svg. %>\n' + brandSvg(128).replace('width="1024" height="1024"', 'width="80" height="80" aria-hidden="true" focusable="false"'));
for (const size of [192, 512]) {
  await writeFile(`src/public/icons/icon-${size}.png`, await brandPng(size));
  await writeFile(`src/public/icons/icon-${size}-maskable.png`, await brandPng(size, 'full-bleed'));
}
await writeFile('src/public/icons/apple-touch-icon.png', await brandPng(180, 'full-bleed'));

// BIMI uses the filter-free optical artwork and the SVG Tiny PS profile.
const bimi = brandSvg(32).replace('width="32" height="32"', 'version="1.2" baseProfile="tiny-ps"')
  .replace('viewBox="0 0 32 32">', 'viewBox="0 0 32 32">\n  <title>ByWave Calendar</title>');
await writeFile('src/public/bimi/logo.svg', bimi);

await writeFile('apps/ios/ByWaveCalendar/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png', await brandPng(1024, 'full-bleed'));
const android = 'apps/android/ByWaveCalendar/app/src/main/res';
for (const [density, size] of [['mdpi',48],['hdpi',72],['xhdpi',96],['xxhdpi',144],['xxxhdpi',192]]) {
  await writeFile(`${android}/mipmap-${density}/ic_launcher.png`, await brandPng(size));
  const circle = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><circle cx="${size/2}" cy="${size/2}" r="${size/2}" fill="white"/></svg>`);
  await sharp(await brandPng(size, 'full-bleed')).ensureAlpha().composite([{input: circle, blend: 'dest-in'}])
    .png().toFile(`${android}/mipmap-${density}/ic_launcher_round.png`);
}
await mkdir(`${android}/drawable-nodpi`, { recursive: true });
for (const variant of ['foreground', 'background', 'monochrome']) {
  await writeFile(`${android}/drawable-nodpi/ic_launcher_${variant}.png`, await brandPng(432, variant));
}
console.log('Generated web, PWA, email, iOS and Android brand assets.');
